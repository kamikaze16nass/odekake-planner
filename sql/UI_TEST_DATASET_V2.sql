select
  s.invite_code,
  s.title,
  s.status,
  count(distinct m.id) as member_count,
  count(distinct r.id) as response_count
from public.schedules s
left join public.members m
  on m.schedule_id = s.id
left join public.responses r
  on r.schedule_id = s.id
where s.invite_code like 'UIT%'
group by
  s.id,
  s.invite_code,
  s.title,
  s.status
order by
  s.invite_code;
