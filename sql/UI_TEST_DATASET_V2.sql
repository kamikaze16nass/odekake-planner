-- ============================================================
-- UI TEST DATASET V2
-- ============================================================
-- このSQLは、UI確認・結合テスト・回帰テストを行うために、
-- テスト用の予定・参加者・回答データをSupabaseへ登録するSQLです。
--
-- 【このSQLを実行するタイミング】
-- アプリの主要画面や集計表示をまとめて確認したいときに実行します。
--
-- 先にテスト対象のブラウザでアプリを一度起動し、
-- Anonymous Authによるユーザー識別と表示名設定を完了してから
-- このSQLを実行してください。
--
-- ============================================================
-- 【実行前の準備】
-- ============================================================
-- 1. テストデータを表示したいブラウザでアプリを開きます。
--
-- 2. 初回利用の場合は、
--    アプリ上で表示名を設定してください。
--
-- 3. ブラウザのLocal Storageから、
--    現在のSupabase Auth UIDを確認します。
--
--    確認例：
--    F12
--    → Application
--    → Local Storage
--    → 現在開いているアプリのURL
--    → 「sb-...-auth-token」のようなSupabase Authの項目
--    → user → id
--
-- 4. すぐ下にある
--    user_id / user_name の2か所だけ変更します。
--
-- 5. 変更後、このSQLをSupabase SQL Editorで実行します。
--
-- 6. SQL実行後、ブラウザを再読み込みして
--    テストデータが表示されることを確認します。
--
-- ============================================================
-- 【このSQLのルール】
-- ============================================================
-- ・テスト用の招待コードは、すべて「UIT」から始まります。
-- ・実行時は、既存の通常データを削除しません。
-- ・テスト用の地名には、東京都23区内の一般的な駅・エリアを使用しています。
-- ・GitHubに保存するファイルには、実際のSupabase Auth UIDを含めません。
--
-- ============================================================
-- ★ 実行前に変更するのは、すぐ下の2か所だけです
-- ============================================================

create temporary table ui_test_context (
  user_id text not null,
  user_name text not null
) on commit drop;

insert into ui_test_context (
  user_id,
  user_name
)
values (
  '00000000-0000-0000-0000-000000000000', -- ① 自分のSupabase Auth UIDに変更
  '私の名前'                                -- ② テストで使用する表示名に変更
);

-- ============================================================
-- 実行前チェック
-- ============================================================
-- 上の2項目が未変更、またはUIDがSupabase Authに存在しない場合は、
-- テストデータを削除・登録する前にここで処理を停止します。

do $$
declare
  test_user_id text;
  test_user_name text;
begin
  select user_id, user_name
    into test_user_id, test_user_name
  from ui_test_context
  limit 1;

  if test_user_id = '00000000-0000-0000-0000-000000000000' then
    raise exception
      'UI_TEST_DATASET_V2: user_idを自分のSupabase Auth UIDに変更してから実行してください。';
  end if;

  if not exists (
    select 1
    from auth.users
    where id::text = test_user_id
  ) then
    raise exception
      'UI_TEST_DATASET_V2: 指定したuser_idがauth.usersに存在しません。UIDを確認してください。';
  end if;

  if test_user_name = ('私の' || '名前') then
    raise exception
      'UI_TEST_DATASET_V2: user_nameをテストで使用する表示名に変更してから実行してください。';
  end if;
end
$$;


