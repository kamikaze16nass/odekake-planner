do $$
declare
  test_user_id uuid;
  test_user_name text;
begin
  select user_id, user_name
    into test_user_id, test_user_name
  from ui_test_context
  limit 1;

  if test_user_id = '00000000-0000-0000-0000-000000000000' then
    raise exception
      'UI_TEST_DATASET_V3: user_idを自分のSupabase Auth UIDに変更してから実行してください。';
  end if;

  if not exists (
    select 1
    from auth.users
    where id = test_user_id
  ) then
    raise exception
      'UI_TEST_DATASET_V3: 指定したuser_idがauth.usersに存在しません。UIDを確認してください。';
  end if;

  if test_user_name = ('私の' || '名前') then
    raise exception
      'UI_TEST_DATASET_V3: user_nameをテストで使用する表示名に変更してから実行してください。';
  end if;
end
$$;

-- ============================================================
-- 現行DBスキーマとの互換性チェック
-- ============================================================
-- このV3は以下を前提とします。
--   schedules.created_by : text
--   members.user_id      : text
--   responses.user_id    : uuid
--   responses.preferred_areas : text[]
--   schedules.transport_policy : text

do $$
declare
  schedules_created_by_type text;
  members_user_id_type text;
  responses_user_id_type text;
  preferred_areas_udt text;
  transport_policy_type text;
begin
  select data_type
    into schedules_created_by_type
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'schedules'
    and column_name = 'created_by';

  select data_type
    into members_user_id_type
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'members'
    and column_name = 'user_id';

  select data_type
    into responses_user_id_type
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'responses'
    and column_name = 'user_id';

  select udt_name
    into preferred_areas_udt
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'responses'
    and column_name = 'preferred_areas';

  select data_type
    into transport_policy_type
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'schedules'
    and column_name = 'transport_policy';

  if schedules_created_by_type is distinct from 'text' then
    raise exception
      'UI_TEST_DATASET_V3: schedules.created_by は text 前提です。現在: %',
      coalesce(schedules_created_by_type, '列なし');
  end if;

  if members_user_id_type is distinct from 'text' then
    raise exception
      'UI_TEST_DATASET_V3: members.user_id は text 前提です。現在: %',
      coalesce(members_user_id_type, '列なし');
  end if;

  if responses_user_id_type is distinct from 'uuid' then
    raise exception
      'UI_TEST_DATASET_V3: responses.user_id は uuid 前提です。現在: %',
      coalesce(responses_user_id_type, '列なし');
  end if;

  if preferred_areas_udt is distinct from '_text' then
    raise exception
      'UI_TEST_DATASET_V3: responses.preferred_areas は text[] 前提です。現在: %',
      coalesce(preferred_areas_udt, '列なし');
  end if;

  if transport_policy_type is distinct from 'text' then
    raise exception
      'UI_TEST_DATASET_V3: schedules.transport_policy は text 前提です。現在: %',
      coalesce(transport_policy_type, '列なし');
  end if;
end
$$;

