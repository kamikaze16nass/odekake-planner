select
  s.invite_code,
  s.title,
  count(distinct m.user_id) as member_count,
  count(distinct r.user_id) as response_count
from public.schedules s
left join public.members m
  on m.schedule_id = s.id
left join public.responses r
  on r.schedule_id = s.id
where s.invite_code like 'UIT%'
group by s.id, s.invite_code, s.title
order by s.invite_code;

-- 投票集計確認用
